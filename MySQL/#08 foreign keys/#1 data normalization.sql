database normalizaion은 normal form에 따라 관계형 데이터베이스를 구조화하는 과정이다

5개의 normal form이 있다.

database를 설계하고 디자인하는 방법에 대한 모범 사례 같은 것이다

취업 면접에서 나올 수도 있다

normalization라는 이름이 어디서 유래했는가

normalization은 DB에서 중복되는 data를 제거할 수 있게 해준다

그리고 해당 data가 한 곳에만 저장되도록 한다

만약 data가 중복되지 않았다면 데이터 수정/ 추가/ 삭제를 쉽고 빠르게 만들어

데이터를 일관되게 유지할 수 있다

중복된 data가 있는 곳을 전부 기억하고 각각 업데이트하는 대신 한 곳에서만 업데이트를 하면 되기 때문이다

이것이 데이터 정규화다



데이터베이스 정규화
정규화는 데이터가 중복되지 않도록 테이블을 잘게 나눠서, 오류를 줄이고, 관리하기 쉽게 만드는 방법

정규화의 핵심 목표

	1. 중복 제거: 같은 데이터가 여러 번 쓰지 않도록 함
	
	2. 데이터 무결성 유지: 데이터가 정확하고 일관성 있게 함
	
	3. 관리 편함: 수정할 때 한 곳만 바꾸면 끝
	
	
데이터 무결성이란
: 데이터가 정확하고, 일관되며, 변하지 않고, 신뢰 가능한 상태로 유지되는 것을 의미한다.

쉽게 말하면
: 데이터가 원래 의도한 대로 그대로 유지되는 것.
잘못되거나, 사라지거나, 중복되거나, 조작되지 않도록 보호하는 것.