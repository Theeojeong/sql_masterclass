A - Atomicity (원자성)

	"전부 아니면 전무" - All or Nothing

C - Consistency (일관성)

	"규칙을 절대 어기지 않는다"
	설명:
	
	데이터베이스의 제약조건과 규칙을 항상 지켜야 합니다
	트랜잭션 전후로 데이터베이스는 항상 유효한 상태여야 합니다

I - Isolation (격리성)

	"다른 사람 작업이 내 작업을 방해하지 못한다"
	
	설명:
	- 여러 트랜잭션이 동시에 실행되어도
	- 각 트랜잭션은 혼자 실행되는 것처럼 동작해야 합니다
	
D - Durability (지속성)
	"한 번 저장하면 절대 안 잃어버린다"
	설명:
	
	COMMIT이 완료되면
	정전, 시스템 다운, 크래시가 나도
	데이터는 절대 사라지지 않습니다