-- 가장 엄격한 트랜잭션 격리이다

-- 모든 트랜잭션이 동시에 실행했을 때랑 하나씩 실행할 때와 다르 결과가 나타난다면

-- 트랜잭션이 격리되지 않은 것이다 

-- 데이터베이스가 serializable 격리 수준에서 실행하고 있는 트랜잭션들이

-- 동시에 실행했을 때와 순차적으로 실행했을 때 서로 다른 결과를 갖는다는 것을 알게 되면

-- 에러를 발생시킬 것이다



데이터베이스에서 Serialization Anomaly (직렬화 이상)는 동시성 제어와 관련된 가장 심각한 문제입니다. 

정의: 여러 트랜잭션이 동시에 실행될 때, 그 최종 결과가 마치 트랜잭션들을 하나씩 
순서대로(직렬로) 처리했을 때 나올 수 있는 어떤 결과와도 일치하지 않는 현상을 의미합니다. 

즉, 각 트랜잭션 자체는 논리적으로 올바르게 설계되었더라도, 
데이터베이스 시스템이 트랜잭션 처리를 너무 약하게 격리하면 예상치 못한 데이터 불일치가 발생하는 것입니다.

왜 중요한가요?

데이터베이스 트랜잭션의 최고 목표는 **"직렬성(Serializability)"**을 보장하는 것입니다. 

이는 여러 트랜잭션을 동시에 돌려도, 그 결과는 항상 순차적으로 실행했을 때와 같아야 한다는 원칙입니다. 

Serialization Anomaly는 바로 이 직렬성이 깨졌을 때 발생합니다.